def generate_recipe_from_image(image):
    """Generate a recipe from a single food image"""
    # Prepare the input following your training format
    # image = process_image_test(image)
    messages = [
        {
            "role": "system",
            "content": [{"type": "text", "text": SYSTEM_MESSAGE}],
        },
        {
            "role": "user",
            "content": [
                {"type": "image", "image": image},
                {"type": "text", "text": USER_PROMPT},
            ],
        }
    ]

    # Process the input
    text = processor.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=False
    )
    # print(f"Processed text: {text}")

    inputs = processor(
        text=text,
        images=image,
        return_tensors="pt",
        padding=True
    ).to(model_inference.device)

    # Generate output
    stop_token_ids = [
        processor.tokenizer.eos_token_id,
        processor.tokenizer.convert_tokens_to_ids("<end_of_turn>")
    ]

    generation_params = {
        "max_new_tokens": 512,  # Increased for longer recipes
        "do_sample": True,
        "temperature": 0.7,
        "top_p": 0.9,
        "eos_token_id": stop_token_ids,
    }

    with torch.no_grad():
        outputs = model_inference.generate(**inputs, **generation_params)

    # Decode the output (skip the input part)
    input_length = inputs.input_ids.shape[1]
    generated_ids = outputs[0][input_length:]
    recipe = processor.decode(
        generated_ids,
        skip_special_tokens=True,
        clean_up_tokenization_spaces=True
    ).strip()
    recipe = recipe.lstrip("b'").rstrip("'")

    return recipe

def compute_rouge(pred, ref):
    score = rouge.compute(predictions=[pred], references=[ref], rouge_types=["rougeL"])["rougeL"]
    return score

